CREATE POLICY "Allow public read penalty_matches"
  ON public.penalty_matches FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow anon insert penalty_matches" ON public.penalty_matches;
CREATE POLICY "Allow anon insert penalty_matches"
  ON public.penalty_matches FOR INSERT
