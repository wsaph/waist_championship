-- supabase_schema.sql
-- PostgreSQL Schema for Pikachu Chibi Beach Volleyball (1v1 & 2v2)
-- Run this script in the Supabase SQL Editor.
-- Note: Live gameplay positions are NEVER written to PostgreSQL; only completed match results are saved once by the Host.

-- 1. Match History Table
CREATE TABLE IF NOT EXISTS public.match_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_uid TEXT UNIQUE NOT NULL,
  room_code VARCHAR(8) NOT NULL,
  mode VARCHAR(8) NOT NULL CHECK (mode IN ('1v1', '2v2')),
  winning_team VARCHAR(8) NOT NULL CHECK (winning_team IN ('blue', 'red')),
  winners JSONB NOT NULL DEFAULT '[]'::jsonb,
  losers JSONB NOT NULL DEFAULT '[]'::jsonb,
  score_blue INTEGER NOT NULL DEFAULT 0,
  score_red INTEGER NOT NULL DEFAULT 0,
  duration_seconds INTEGER NOT NULL DEFAULT 0,
  played_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_match_history_played_at
  ON public.match_history (played_at DESC);

CREATE INDEX IF NOT EXISTS idx_match_history_room_code
  ON public.match_history (room_code);

-- 2. Player Stats / Leaderboard Table
CREATE TABLE IF NOT EXISTS public.player_stats (
  player_name TEXT PRIMARY KEY,
  skin VARCHAR(24) NOT NULL DEFAULT 'pikamouse',
  wins INTEGER NOT NULL DEFAULT 0,
  losses INTEGER NOT NULL DEFAULT 0,
  total_points INTEGER NOT NULL DEFAULT 0,
  matches_played INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_player_stats_leaderboard
  ON public.player_stats (wins DESC, total_points DESC);

-- 3. Atomic RPC Function (called once by Host when a match finishes)
CREATE OR REPLACE FUNCTION public.record_volleyball_match(
  p_match_uid TEXT,
  p_room_code TEXT,
  p_mode TEXT,
  p_winning_team TEXT,
  p_winners JSONB,
  p_losers JSONB,
  p_score_blue INTEGER,
  p_score_red INTEGER,
  p_duration_seconds INTEGER,
  p_player_entries JSONB
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_inserted_id BIGINT;
  v_entry JSONB;
  v_name TEXT;
  v_skin TEXT;
  v_won BOOLEAN;
  v_pts INTEGER;
BEGIN
  INSERT INTO public.match_history (
    match_uid,
    room_code,
    mode,
    winning_team,
    winners,
    losers,
    score_blue,
    score_red,
    duration_seconds
  )
  VALUES (
    p_match_uid,
    p_room_code,
    p_mode,
    p_winning_team,
    p_winners,
    p_losers,
    p_score_blue,
    p_score_red,
    p_duration_seconds
  )
  ON CONFLICT (match_uid) DO NOTHING
  RETURNING id INTO v_inserted_id;

  -- Prevent duplicate stat increments if retried
  IF v_inserted_id IS NULL THEN
    RETURN FALSE;
  END IF;

  FOR v_entry IN SELECT * FROM jsonb_array_elements(p_player_entries)
  LOOP
    v_name := trim(COALESCE(v_entry->>'name', ''));
    v_skin := COALESCE(v_entry->>'skin', 'pikamouse');
    v_won := COALESCE((v_entry->>'won')::boolean, FALSE);
    v_pts := GREATEST(0, COALESCE((v_entry->>'points')::integer, 0));

    IF v_name <> '' THEN
      INSERT INTO public.player_stats (
        player_name,
        skin,
        wins,
        losses,
        total_points,
        matches_played,
        updated_at
      )
      VALUES (
        v_name,
        v_skin,
        CASE WHEN v_won THEN 1 ELSE 0 END,
        CASE WHEN v_won THEN 0 ELSE 1 END,
        v_pts,
        1,
        NOW()
      )
      ON CONFLICT (player_name) DO UPDATE SET
        skin = EXCLUDED.skin,
        wins = public.player_stats.wins + (CASE WHEN v_won THEN 1 ELSE 0 END),
        losses = public.player_stats.losses + (CASE WHEN v_won THEN 0 ELSE 1 END),
        total_points = public.player_stats.total_points + v_pts,
        matches_played = public.player_stats.matches_played + 1,
        updated_at = NOW();
    END IF;
  END LOOP;

  RETURN TRUE;
END;
$$;

-- 4. Row Level Security (Public Read + Anon Insert at Match End)
ALTER TABLE public.match_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.player_stats ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read match_history" ON public.match_history;
CREATE POLICY "Allow public read match_history"
  ON public.match_history FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow anon insert match_history" ON public.match_history;
CREATE POLICY "Allow anon insert match_history"
  ON public.match_history FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read player_stats" ON public.player_stats;
CREATE POLICY "Allow public read player_stats"
  ON public.player_stats FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS "Allow anon insert player_stats" ON public.player_stats;
CREATE POLICY "Allow anon insert player_stats"
  ON public.player_stats FOR INSERT
  TO anon, authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update player_stats" ON public.player_stats;
CREATE POLICY "Allow anon update player_stats"
  ON public.player_stats FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (true);

-- ============================================================================
-- 5. 3D Penalty Shootout Online 1v1 Schema (`penalty_matches` & `player_stats`)
-- Saved strictly ONCE at match end by the Host (zero DB writes during turns).
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.penalty_matches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_uid TEXT UNIQUE NOT NULL,
  room_code VARCHAR(8) NOT NULL,
  winner_name TEXT NOT NULL,
  loser_name TEXT NOT NULL,
  winner_model VARCHAR(48) NOT NULL DEFAULT 'fox_hero',
  loser_model VARCHAR(48) NOT NULL DEFAULT 'bunny_hero',
  winner_score INTEGER NOT NULL DEFAULT 0,
  loser_score INTEGER NOT NULL DEFAULT 0,
  total_rounds INTEGER NOT NULL DEFAULT 5,
  sudden_death BOOLEAN NOT NULL DEFAULT FALSE,
  duration_seconds INTEGER NOT NULL DEFAULT 0,
  played_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_penalty_matches_played_at
  ON public.penalty_matches (played_at DESC);

ALTER TABLE public.player_stats
  ADD COLUMN IF NOT EXISTS penalty_wins INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.player_stats
  ADD COLUMN IF NOT EXISTS penalty_losses INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.player_stats
  ADD COLUMN IF NOT EXISTS penalty_goals INTEGER NOT NULL DEFAULT 0;
ALTER TABLE public.player_stats
  ADD COLUMN IF NOT EXISTS penalty_matches_played INTEGER NOT NULL DEFAULT 0;

CREATE OR REPLACE FUNCTION public.record_penalty_match(
  p_match_uid TEXT,
  p_room_code TEXT,
  p_winner_name TEXT,
  p_loser_name TEXT,
  p_winner_model TEXT,
  p_loser_model TEXT,
  p_winner_score INTEGER,
  p_loser_score INTEGER,
  p_total_rounds INTEGER,
  p_sudden_death BOOLEAN,
  p_duration_seconds INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_inserted_id BIGINT;
BEGIN
  INSERT INTO public.penalty_matches (
    match_uid,
    room_code,
    winner_name,
    loser_name,
    winner_model,
    loser_model,
    winner_score,
    loser_score,
    total_rounds,
    sudden_death,
    duration_seconds
  )
  VALUES (
    p_match_uid,
    p_room_code,
    p_winner_name,
    p_loser_name,
    p_winner_model,
    p_loser_model,
    p_winner_score,
    p_loser_score,
    p_total_rounds,
    p_sudden_death,
    p_duration_seconds
  )
  ON CONFLICT (match_uid) DO NOTHING
  RETURNING id INTO v_inserted_id;

  IF v_inserted_id IS NULL THEN
    RETURN FALSE;
  END IF;

  IF trim(COALESCE(p_winner_name, '')) <> '' THEN
    INSERT INTO public.player_stats (
      player_name,
      skin,
      wins,
      losses,
      total_points,
      matches_played,
      penalty_wins,
      penalty_losses,
      penalty_goals,
      penalty_matches_played,
      updated_at
    )
    VALUES (
      trim(p_winner_name),
      COALESCE(p_winner_model, 'fox_hero'),
      1,
      0,
      GREATEST(0, p_winner_score),
      1,
      1,
      0,
      GREATEST(0, p_winner_score),
      1,
      NOW()
    )
    ON CONFLICT (player_name) DO UPDATE SET
      skin = EXCLUDED.skin,
      wins = public.player_stats.wins + 1,
      total_points = public.player_stats.total_points + GREATEST(0, p_winner_score),
      matches_played = public.player_stats.matches_played + 1,
      penalty_wins = public.player_stats.penalty_wins + 1,
      penalty_goals = public.player_stats.penalty_goals + GREATEST(0, p_winner_score),
      penalty_matches_played = public.player_stats.penalty_matches_played + 1,
      updated_at = NOW();
  END IF;

  IF trim(COALESCE(p_loser_name, '')) <> '' THEN
    INSERT INTO public.player_stats (
      player_name,
      skin,
      wins,
      losses,
      total_points,
      matches_played,
      penalty_wins,
      penalty_losses,
      penalty_goals,
      penalty_matches_played,
      updated_at
    )
    VALUES (
      trim(p_loser_name),
      COALESCE(p_loser_model, 'bunny_hero'),
      0,
      1,
      GREATEST(0, p_loser_score),
      1,
      0,
      1,
      GREATEST(0, p_loser_score),
      1,
      NOW()
    )
    ON CONFLICT (player_name) DO UPDATE SET
      skin = EXCLUDED.skin,
      losses = public.player_stats.losses + 1,
      total_points = public.player_stats.total_points + GREATEST(0, p_loser_score),
      matches_played = public.player_stats.matches_played + 1,
      penalty_losses = public.player_stats.penalty_losses + 1,
      penalty_goals = public.player_stats.penalty_goals + GREATEST(0, p_loser_score),
      penalty_matches_played = public.player_stats.penalty_matches_played + 1,
      updated_at = NOW();
  END IF;

  RETURN TRUE;
END;
$$;

ALTER TABLE public.penalty_matches ENABLE ROW LEVEL SECURITY;

